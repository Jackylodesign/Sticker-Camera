// Copies the sticker look (border + shadow) from lib/sticker.ts into the
// Figma plugin, so the web app is the only place to change it.
// Figma needs the plugin window as one HTML file, so the code is pasted into
// figma-plugin/ui.html between the BEGIN/END GENERATED lines.
// Run: npm run build:plugin   (then commit figma-plugin/ui.html)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const UI_HTML = fileURLToPath(new URL("../figma-plugin/ui.html", import.meta.url));

const BEGIN = "  // BEGIN GENERATED by npm run build:plugin. Don't edit by hand.\n";
const END = "  // END GENERATED\n";

/** The bundled code: a global `StickerStyle` with prepareSticker and renderSticker. */
export async function bundleStickerStyle() {
  const result = await build({
    stdin: {
      contents: 'export { prepareSticker, renderSticker } from "./lib/sticker";',
      resolveDir: ROOT,
      loader: "ts",
    },
    absWorkingDir: ROOT,
    bundle: true,
    write: false,
    format: "iife",
    globalName: "StickerStyle",
    platform: "browser",
    target: "es2020",
    charset: "utf8",
    legalComments: "none",
  });
  return result.outputFiles[0].text;
}

/** ui.html with the generated part replaced by a fresh bundle. */
export async function buildUiHtml(html = readFileSync(UI_HTML, "utf8")) {
  const start = html.indexOf(BEGIN);
  const end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error("ui.html is missing the BEGIN/END GENERATED lines");
  return html.slice(0, start + BEGIN.length) + (await bundleStickerStyle()) + html.slice(end);
}

// Only when run as a script (not when a test imports this file).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(UI_HTML, await buildUiHtml());
  console.log("Updated figma-plugin/ui.html");
}
